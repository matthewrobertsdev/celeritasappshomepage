<h2 class="left-h2">How do I quit Celebratation Lights?</h2>
<p class="body-p">You have various ways to quit Celebration Lights.  You can click on one of the lights and then do command-q.  You can also click on one of the lights and then find the Celbrations Lights menu in the menu bar and click on it and select quit.  Lastly, in the top left of the screen there are two small buttons. Click the one on the left to get a popover which will have a button to confirm you want to quit.  Click it to quit.</p>
